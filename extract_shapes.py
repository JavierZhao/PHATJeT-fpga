"""
Dump exact layer shapes + parameter counts for the synthesizable PHAT-JeT.

Handoff deliverable #1 (`shapes.md`). All analytical hardware estimates key off
this file, so it is generated from the model code -- never hand-maintained.

Builds the FLOAT graph (quantized=False): identical topology and shapes to the
quantized one, but importable without hgq/da4ml. Run in any env with keras 3.

Usage:  KERAS_BACKEND=torch python extract_shapes.py
"""

import os
import sys

os.environ.setdefault("KERAS_BACKEND", "torch")
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

from phat_jet_k3 import build_phat_jet_k3

# Config actually built by train_qat.build_qat_model(): quantized=True, use_ln=False.
# Everything else is build_phat_jet_k3's default.
def _e(name, default, cast=str):
    return cast(os.environ.get(name, default))


CFG = dict(
    num_particles=_e("PJ_PARTICLES", 64, int),
    num_feats=3,
    d_model=_e("PJ_D_MODEL", 16, int),
    num_heads=_e("PJ_HEADS", 4, int),
    patch_size=_e("PJ_PATCH", 8, int),
    ffn_mult=_e("PJ_FFN_MULT", 1, int),
    n_classes=5,
    use_gmp=True,
    use_ln=False,
    gmp_bins=8,
    gmp_lo=_e("PJ_GMP_LO", -1.6, float),
    gmp_hi=_e("PJ_GMP_HI", 1.6, float),
    patch_tokenizer=_e("PJ_TOKENIZER", "mean"),
    pre_norm=_e("PJ_PRE_NORM", "tanh") or None,
)


def shape_str(s):
    if s is None:
        return "-"
    if isinstance(s, (list, tuple)) and s and isinstance(s[0], (list, tuple)):
        return ", ".join(shape_str(x) for x in s)
    return "(" + ", ".join("B" if d is None else str(d) for d in s) + ")"


def main():
    model = build_phat_jet_k3(**CFG)

    rows = []
    for layer in model.layers:
        try:
            ish = shape_str(layer.input.shape if hasattr(layer, "input") else None)
        except Exception:
            ish = "-"
        try:
            osh = shape_str(layer.output.shape)
        except Exception:
            osh = "-"
        rows.append((layer.name, layer.__class__.__name__, ish, osh, layer.count_params()))

    total = model.count_params()

    with open("shapes.md", "w") as f:
        f.write("# PHAT-JeT (synthesizable) — exact layer shapes\n\n")
        f.write("Generated by `extract_shapes.py` from `phat_jet_k3.py`. Do not edit by hand.\n\n")
        f.write("Config: " + ", ".join(f"`{k}={v}`" for k, v in CFG.items()) + "\n\n")
        f.write(f"Total trainable parameters: **{total:,}**\n\n")
        f.write("| # | Layer | Type | Input | Output | Params |\n")
        f.write("|---|---|---|---|---|---|\n")
        for i, (n, t, ish, osh, p) in enumerate(rows):
            f.write(f"| {i} | `{n}` | {t} | {ish} | {osh} | {p:,} |\n")

    print(f"{len(rows)} layers, {total:,} params -> shapes.md")
    for n, t, ish, osh, p in rows:
        print(f"  {n:<26} {t:<22} {ish:<20} -> {osh:<20} {p:>7,}")


if __name__ == "__main__":
    main()
